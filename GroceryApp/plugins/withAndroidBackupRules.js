const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

/**
 * Keeps PantryRun's data out of Android Auto Backup and device-to-device
 * transfer.
 *
 * Why opt out entirely rather than back up "the safe parts": everything the app
 * stores is either ciphertext or the keys to it, and the keys cannot travel.
 *
 *   - expo-secure-store values are encrypted with an Android Keystore key that is
 *     bound to this device and is never backed up. A restored SecureStore
 *     preferences file is undecryptable on the new device, and expo-secure-store
 *     then fails reads instead of starting fresh.
 *   - The WatermelonDB database's sensitive fields are encrypted with the family
 *     master key, which lives in that same SecureStore. A restored database
 *     without its key is a pile of undecryptable rows that looks like data.
 *
 * The supported way to move to a new phone is the recovery phrase or joining from
 * another family device, which re-derives keys and re-syncs. So the manifest sets
 * android:allowBackup="false" (Android 11 and lower: no backup at all) AND points
 * android:dataExtractionRules at a resource that excludes every domain, because
 * on Android 12+ allowBackup="false" still permits device-to-device transfer
 * unless extraction rules exclude it.
 *
 * Same pattern as withNetworkSecurityConfig.js: this plugin is the single place
 * the intent lives, so a `prebuild --clean` reproduces the committed android/
 * tree. plugins/__checks__/release-config.check.js asserts they match.
 */

const RES_PATH = "app/src/main/res/xml/data_extraction_rules.xml";

const DOMAINS = ["root", "file", "database", "sharedpref", "external"];
const excludes = DOMAINS.map((d) => `    <exclude domain="${d}" path="." />`).join("\n");

/**
 * Canonical contents of res/xml/data_extraction_rules.xml.
 * Excluding "." in every domain excludes everything: with no <include>, the
 * default is "include all", and each exclude removes one domain from it.
 */
const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
  PantryRun opts out of Android cloud backup and device-to-device transfer.
  Restored SecureStore values and database rows would be undecryptable on the
  new device (their Keystore key does not transfer). Moving phones uses the
  recovery phrase or a family device instead.

  Generated by plugins/withAndroidBackupRules.js on prebuild. Edit the plugin,
  not this file.
-->
<data-extraction-rules>
  <cloud-backup>
${excludes}
  </cloud-backup>
  <device-transfer>
${excludes}
  </device-transfer>
</data-extraction-rules>
`;

/** Exported so the release-config check can drive it without a prebuild. */
function setBackupRules(androidManifest) {
  const application = androidManifest.manifest.application?.find((a) =>
    a.$?.["android:name"]?.endsWith(".MainApplication")
  );
  if (!application) {
    throw new Error("AndroidManifest.xml is missing the MainApplication element");
  }
  application.$["android:allowBackup"] = "false";
  application.$["android:dataExtractionRules"] = "@xml/data_extraction_rules";
  // fullBackupContent only matters when backup is allowed on Android 11 and
  // lower; with allowBackup="false" it is dead config, so make sure none lingers.
  delete application.$["android:fullBackupContent"];
  return androidManifest;
}

function withAndroidBackupRules(config) {
  config = withAndroidManifest(config, (cfg) => {
    cfg.modResults = setBackupRules(cfg.modResults);
    return cfg;
  });

  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const dest = path.join(cfg.modRequest.platformProjectRoot, RES_PATH);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, DATA_EXTRACTION_RULES_XML);
      return cfg;
    },
  ]);
}

module.exports = withAndroidBackupRules;
module.exports.setBackupRules = setBackupRules;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
module.exports.RES_PATH = RES_PATH;
